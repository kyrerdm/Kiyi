import AppKit

final class BrightnessManager: ObservableObject {
	static let shared = BrightnessManager()

	@Published private(set) var rawBrightness: Float = 0
	@Published private(set) var animatedBrightness: Float = 0
	@Published private(set) var lastChangeAt: Date = .distantPast

	private let visibleDuration: TimeInterval = 1.2
	private let client = XPCHelperClient.shared
	private var pendingAdjustment: Task<Void, Never>?

	private init() { refresh() }

	var shouldShowOverlay: Bool { Date().timeIntervalSince(lastChangeAt) < visibleDuration }

	func refresh() {
		Task { @MainActor in
			if let current = await client.currentScreenBrightness() {
				publish(brightness: current, touchDate: false)
			}
		}
	}

	@MainActor func setRelative(delta: Float) {
		adjust(showIndicator: true) { max(0, min(1, $0 + delta)) }
	}

	@MainActor func setAbsolute(value: Float) {
		adjust { _ in max(0, min(1, value)) }
	}

	@MainActor private func adjust(showIndicator: Bool = false, target: @escaping (Float) -> Float) {
		let previous = pendingAdjustment
		pendingAdjustment = Task { @MainActor in
			await previous?.value
			let current = await client.currentScreenBrightness() ?? rawBrightness
			let level = target(current)
			guard await client.setScreenBrightness(level) else {
				refresh()
				return
			}
			publish(brightness: level, touchDate: true)
			if showIndicator {
				BoringViewCoordinator.shared.toggleSneakPeek(status: true, type: .brightness, value: CGFloat(level))
			}
		}
	}

	private func publish(brightness: Float, touchDate: Bool) {
		DispatchQueue.main.async {
			if self.rawBrightness != brightness || touchDate {
				if touchDate { self.lastChangeAt = Date() }
				self.rawBrightness = brightness
				self.animatedBrightness = brightness
			}
		}
	}
}

